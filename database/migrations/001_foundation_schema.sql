-- PROJEX ENTERPRISE 001: foundation schema (organization, identity, projects).
-- Hand-written to mirror ProjexDbContext (snake_case columns). Run as projex_owner.
-- VERIFY against `dotnet ef migrations script` output before the first real deployment.
CREATE SCHEMA IF NOT EXISTS organization;
CREATE SCHEMA IF NOT EXISTS identity;
CREATE SCHEMA IF NOT EXISTS projects;

CREATE TABLE organization.tenants (
    id uuid PRIMARY KEY,
    key varchar(60) NOT NULL,
    name varchar(200) NOT NULL,
    status varchar(20) NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT ck_tenant_status CHECK (status IN ('Active','Suspended','Closed'))
);
CREATE UNIQUE INDEX ux_tenants_key ON organization.tenants(key);

CREATE TABLE organization.companies (
    id uuid PRIMARY KEY,
    tenant_id uuid NOT NULL REFERENCES organization.tenants(id),
    code varchar(40) NOT NULL,
    name varchar(200) NOT NULL,
    is_active boolean NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT uq_companies_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT uq_companies_tenant_code UNIQUE (tenant_id, code)
);

CREATE TABLE organization.branches (
    id uuid PRIMARY KEY,
    tenant_id uuid NOT NULL,
    company_id uuid NOT NULL,
    code varchar(40) NOT NULL,
    name varchar(200) NOT NULL,
    is_active boolean NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT uq_branches_tenant_company_id UNIQUE (tenant_id, company_id, id),
    CONSTRAINT uq_branches_tenant_company_code UNIQUE (tenant_id, company_id, code),
    CONSTRAINT fk_branches_company FOREIGN KEY (tenant_id, company_id)
        REFERENCES organization.companies(tenant_id, id) ON DELETE RESTRICT
);

CREATE TABLE projects.projects (
    id uuid PRIMARY KEY,
    tenant_id uuid NOT NULL,
    company_id uuid NOT NULL,
    branch_id uuid NULL,
    code varchar(50) NOT NULL,
    name varchar(200) NOT NULL,
    currency_code char(3) NOT NULL,
    time_zone varchar(80) NOT NULL,
    status varchar(20) NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT uq_projects_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT uq_projects_tenant_company_code UNIQUE (tenant_id, company_id, code),
    CONSTRAINT fk_projects_company FOREIGN KEY (tenant_id, company_id)
        REFERENCES organization.companies(tenant_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_projects_branch FOREIGN KEY (tenant_id, company_id, branch_id)
        REFERENCES organization.branches(tenant_id, company_id, id) ON DELETE RESTRICT,
    CONSTRAINT ck_project_status CHECK (status IN ('Draft','Active','OnHold','Completed','Cancelled','Archived'))
);
CREATE INDEX ix_projects_tenant_company_status ON projects.projects(tenant_id, company_id, status);

-- ASP.NET Core Identity tables (renamed by the EF model).
CREATE TABLE identity.users (
    id uuid PRIMARY KEY,
    tenant_id uuid NOT NULL REFERENCES organization.tenants(id),
    is_active boolean NOT NULL DEFAULT true,
    user_name varchar(256) NULL,
    normalized_user_name varchar(256) NULL,
    email varchar(256) NULL,
    normalized_email varchar(256) NULL,
    email_confirmed boolean NOT NULL,
    password_hash text NULL,
    security_stamp text NULL,
    concurrency_stamp text NULL,
    phone_number text NULL,
    phone_number_confirmed boolean NOT NULL,
    two_factor_enabled boolean NOT NULL,
    lockout_end timestamptz NULL,
    lockout_enabled boolean NOT NULL,
    access_failed_count integer NOT NULL
);
CREATE UNIQUE INDEX ux_users_normalized_user_name ON identity.users(normalized_user_name);
CREATE UNIQUE INDEX ux_users_tenant_normalized_email ON identity.users(tenant_id, normalized_email);

CREATE TABLE identity.identity_roles (
    id uuid PRIMARY KEY,
    name varchar(256) NULL,
    normalized_name varchar(256) NULL,
    concurrency_stamp text NULL
);
CREATE UNIQUE INDEX ux_identity_roles_normalized_name ON identity.identity_roles(normalized_name);

CREATE TABLE identity.user_roles (
    user_id uuid NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    role_id uuid NOT NULL REFERENCES identity.identity_roles(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, role_id)
);
CREATE TABLE identity.user_claims (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    claim_type text NULL, claim_value text NULL
);
CREATE TABLE identity.role_claims (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id uuid NOT NULL REFERENCES identity.identity_roles(id) ON DELETE CASCADE,
    claim_type text NULL, claim_value text NULL
);
CREATE TABLE identity.user_logins (
    login_provider text NOT NULL, provider_key text NOT NULL, provider_display_name text NULL,
    user_id uuid NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    PRIMARY KEY (login_provider, provider_key)
);
CREATE TABLE identity.user_tokens (
    user_id uuid NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
    login_provider text NOT NULL, name text NOT NULL, value text NULL,
    PRIMARY KEY (user_id, login_provider, name)
);

-- Application RBAC model (not yet used by the API; endpoints still use hard-coded roles).
CREATE TABLE identity.roles (
    id uuid PRIMARY KEY,
    tenant_id uuid NOT NULL REFERENCES organization.tenants(id),
    code varchar(60) NOT NULL,
    name varchar(120) NOT NULL,
    is_system boolean NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT uq_roles_tenant_code UNIQUE (tenant_id, code)
);
CREATE TABLE identity.permissions (
    id uuid PRIMARY KEY,
    code varchar(120) NOT NULL UNIQUE,
    description varchar(300) NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);
CREATE TABLE identity.role_permissions (
    role_id uuid NOT NULL REFERENCES identity.roles(id) ON DELETE CASCADE,
    permission_id uuid NOT NULL REFERENCES identity.permissions(id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);
CREATE TABLE identity.user_memberships (
    id uuid PRIMARY KEY,
    tenant_id uuid NOT NULL,
    company_id uuid NOT NULL,
    user_id uuid NOT NULL REFERENCES identity.users(id),
    is_active boolean NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT uq_user_memberships UNIQUE (tenant_id, company_id, user_id),
    CONSTRAINT fk_user_membership_company FOREIGN KEY (tenant_id, company_id)
        REFERENCES organization.companies(tenant_id, id)
);
